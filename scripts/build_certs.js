/* Regenerate assets/data/certs.js from assets/data/products.js.
   Usage: node scripts/build_certs.js
   Groups the 79 products by their Kemenperin certificate number so a click on
   any certificate number can open a "keterangan sertifikat" popup. */
const fs = require("fs");
const vm = require("vm");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const productsFile = path.join(ROOT, "assets", "data", "products.js");
const outFile = path.join(ROOT, "assets", "data", "certs.js");

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(productsFile, "utf8"), ctx);
const P = ctx.window.PRODUCTS || ctx.PRODUCTS || [];

const MONTHS = ["", "Januari", "Februari", "Maret", "April", "Mei", "Juni",
  "Juli", "Agustus", "September", "Oktober", "November", "Desember"];

const HOLDER = "PT Indonesia Epson Industry";

function parseCert(certNo) {
  const m = String(certNo).trim().match(/^(\d+)\/SJ-IND\.8\/(.+)\/(\d{1,2})\/(\d{4})$/);
  if (!m) return null;
  const month = parseInt(m[3], 10);
  return {
    letterNo: m[1],
    scheme: m[2],                       // "E-TKDN" atau "TKDN/LVI"
    month,
    year: parseInt(m[4], 10),
    period: `${MONTHS[month] || m[3]} ${m[4]}`,
  };
}

const groups = new Map();
for (const p of P) {
  const certNo = String(p.certNo || "").trim();
  if (!certNo) continue;
  if (!groups.has(certNo)) groups.set(certNo, []);
  groups.get(certNo).push({
    model: p.model,
    sku: p.sku,
    category: p.category,
    status: p.status,
    tkdnVal: p.tkdnVal || "—",
    bmpVal: p.bmpVal || "—",
    totalVal: p.totalVal || "—",
    scoreNum: p.scoreNum ?? null,
  });
}

const pct = (v) => parseFloat(String(v).replace(",", ".")) || 0;
const certs = [];
for (const [certNo, products] of groups) {
  const info = parseCert(certNo);
  const scores = products.map((x) => pct(x.totalVal)).filter((n) => n > 0);
  const tkdns = products.map((x) => pct(x.tkdnVal)).filter((n) => n > 0);
  const bmps = [...new Set(products.map((x) => x.bmpVal).filter((v) => v && v !== "—"))];
  const fmt = (n) => n.toFixed(2).replace(".", ",") + "%";
  certs.push({
    certNo,
    isReal: !!info,
    kind: info ? (info.scheme.includes("LVI") ? "TKDN · LVI" : "E-TKDN") : "Referensi katalog",
    scheme: info ? info.scheme : "",
    letterNo: info ? info.letterNo : "",
    period: info ? info.period : "Efektif 28 Agustus 2026",
    year: info ? info.year : 2026,
    holder: HOLDER,
    bmp: bmps.length ? bmps.join(" / ") : "—",
    productCount: products.length,
    tkdnMin: tkdns.length ? fmt(Math.min(...tkdns)) : "—",
    tkdnMax: tkdns.length ? fmt(Math.max(...tkdns)) : "—",
    totalMin: scores.length ? fmt(Math.min(...scores)) : "—",
    totalMax: scores.length ? fmt(Math.max(...scores)) : "—",
    meetsPdn: scores.length ? Math.min(...scores) >= 25 : false,
    products,
  });
}
certs.sort((a, b) => (b.year - a.year) || a.certNo.localeCompare(b.certNo, "id", { numeric: true }));

const banner = `/* Auto-generated by scripts/build_certs.js — jangan edit manual.
   ${certs.filter((c) => c.isReal).length} nomor sertifikat Kemenperin RI, ${P.length} produk.
   Sumber: Katalog TKDN Epson FY25 & Daftar Sertifikat per 28 Agustus 2026. */\n`;
fs.writeFileSync(outFile, banner + "window.TKDN_CERTS = " + JSON.stringify(certs, null, 2) + ";\n", "utf8");
console.log(`wrote ${outFile}`);
console.log(`  ${certs.length} entries (${certs.filter((c) => c.isReal).length} nomor resmi, ${certs.filter((c) => !c.isReal).length} placeholder)`);
console.log(`  ${certs.reduce((a, c) => a + c.products.length, 0)} produk terindeks`);
